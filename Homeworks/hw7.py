# Проверка автомобильного номера Израиля
# Напишите функцию: def is_israel_car_number(number):
# Поддержите два формата:
# 12-345-67
# 123-45-678
# Подходят:
# 12-345-67
# 99-999-99
# 123-45-678
# 456-78-901
# Не подходят:
# 12345678
# 12:345:67
# 1-234-56
# 1234-56-78
#------------------------------------------------------------------
def is_israel_car_number(number):
    pattern = r"(?:[0-9]{2}-[0-9]{3}-[0-9]{2}|[0-9]{3}-[0-9]{2}-[0-9]{3})"
    return re.fullmatch(pattern, number) is not None

for number in ["12-345-67","99-999-99","123-45-678","456-78-901"]:
    assert is_israel_car_number(number)

for number in ["12345678","12:345:67","1-234-56","1234-56-78"]:
    assert not is_israel_car_number(number)

