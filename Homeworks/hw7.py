# 4. Проверка времени
# Напишите функцию: def is_valid_time(time):
# Формат времени: HH:MM (24 часа).
# Подходят:
# 00:00
# 09:30
# 14:45
# 23:59
# Не подходят:
# 24:00
# 12:60
# 8:30
# 123:45
# 12-30

#------------------------------------------------------------------
def is_valid_time(time):
    pattern = r"(?:[01][0-9]|2[0-3]):[0-5][0-9]"
    return re.fullmatch(pattern, time) is not None

for time in ["00:00", "09:30", "14:45", "23:59"]:
    assert is_valid_time(time)

for time in ["24:00", "12:60", "8:30", "123:45", "12-30"]:
    assert not is_valid_time(time)

