# 1. Положительное число меньше 300
# Напишите функцию: def is_positive_less_than_300(value):
# Функция должна возвращать True, если строка содержит целое положительное число от 1 до 299.
# Подходят:
# 1
# 15
# 99
# 100
# 299
# Не подходят:
# 0
# 300
# -5
# 3.14
# Abc

#------------------------------------------------------------------
def is_positive_less_than_300(value):
    pattern = r"(?:[1-9]|[1-9][0-9]|[12][0-9]{2})"
    return re.fullmatch(pattern, value) is not None

for value in ["1", "15", "99", "100", "299"]:
    assert is_positive_less_than_300(value)

for value in ["0", "300", "-5", "3.14", "Abc"]:
    assert not is_positive_less_than_300(value)

