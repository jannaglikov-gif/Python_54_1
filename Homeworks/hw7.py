# 3. Израильский мобильный номер
# Напишите функцию: def is_israel_mobile(phone):
# Допустимы номера:
# 0541234567
# 054-1234567
# +97254-123-4567
# 058-12-34-567
# Не подходят:
# 54-1234567
# 054--12-4567
# +972054-123-4567
# 97254-123-4567

#------------------------------------------------------------------
def is_israel_mobile(phone):
    pattern = r"(?:05[0-9]|\+9725[0-9])(?:-?[0-9]){7}"
    return re.fullmatch(pattern, phone) is not None

for phone in ["0541234567","054-1234567","+97254-123-4567","058-12-34-567"]:
    assert is_israel_mobile(phone)

for phone in ["54-1234567","054--12-4567","+972054-123-4567","97254-1234567"]:
    assert not is_israel_mobile(phone)

